-- supabase/wei3_setup.sql
--
-- 第二個場地（wei3）的資料庫：跟原本場地共用同一個 Supabase 專案（gwwuzmspgvpzlstvafov），
-- 但所有資料表、函式、權限規則都放在獨立的 wei3 schema，資料完全分開。
--   - 前端（docs/config.js）設 SUPABASE_SCHEMA: 'wei3'，supabase-js 的每個查詢／rpc 都只打 wei3。
--   - 結構 = 原本資料庫版的 supabase/schema.sql + policies.sql + functions.sql（這個 repo 的
--     supabase/ 底下有一樣的三個檔案可以對照），差別只有：建在 wei3、每支函式的
--     search_path 固定成 wei3。不含 webhook-trigger.sql（同步 Google 試算表用的，wei3 沒有試算表）。
--   - 帳號：Supabase Auth（auth.users）整個專案共用，但 wei3 有自己的 wei3.profiles 帳號名單，
--     email 用 @wei3.local（原本場地是 @migrated.local），兩邊可以有同名帳號。原本場地的帳號
--     在 wei3.profiles 查不到，登入 wei3 什麼都看不到、什麼都做不了（反過來也一樣）。
--   - 整段包在一個 DO 區塊裡：中間任何一步失敗，整段都不會留下來。
--
-- 套用後還要在 Supabase 後台 Project Settings → Data API → Exposed schemas 加上 wei3，
-- 前端才連得到。

do $wei3$
declare
  _fn record;
  _def text;
  _pos int;
  _head text;
begin
  -- ── wei3 schema 與權限（跟 public 一樣：anon/authenticated/service_role 可用，實際擋人的是 RLS 與函式裡的檢查）──
  create schema if not exists wei3;
  comment on schema wei3 is '第二個場地（GitHub: sky03104/wei3）。資料跟原本場地（public）完全分開。';
  grant usage on schema wei3 to anon, authenticated, service_role;
  alter default privileges for role postgres in schema wei3 grant all on tables to anon, authenticated, service_role;
  alter default privileges for role postgres in schema wei3 grant all on routines to anon, authenticated, service_role;
  alter default privileges for role postgres in schema wei3 grant all on sequences to anon, authenticated, service_role;

  -- 下面 schema.sql／policies.sql 的內容都沒寫 schema 名稱，靠 search_path 讓它們建在 wei3。
  -- 再確認一次真的切過去了，絕不能建到原本場地（public）。
  perform set_config('search_path', 'wei3, pg_temp', true);
  if current_schema() is distinct from 'wei3' then
    raise exception '目前 schema 是 %，不是 wei3，中止', current_schema();
  end if;

