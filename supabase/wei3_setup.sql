-- ── username 登入怎麼接（還沒實作，先記下來）─────────────
--
-- Supabase Auth 認的是 email，現有系統的登入畫面是打帳號（username）+
-- 密碼，不是 email。做法：帳號建立時（見上面的 handle_new_user）幫每個
-- 使用者合成一個內部用、使用者自己不會看到也不用記得的 email，例如
-- `<username>@clawapp.internal`；登入畫面收到 username 之後，先用下面
-- 這支「未登入也能呼叫」的函式換回對應的 email，再拿 email+密碼呼叫
-- Supabase Auth 的 signInWithPassword()——多一次查詢，但使用者體感上
-- 感覺不出來（前端幫忙做這兩步，介面上維持「打帳號登入」不變）。
--
-- security definer 是必要的：呼叫這支函式的當下使用者根本還沒登入
-- （anon role），profiles／auth.users 的 RLS／權限一定擋得住 anon 直接
-- 查表，只能靠這支函式繞過去，但只回傳 email 這一個欄位，不會洩漏
-- 其他使用者資料。
--
-- Phase 5（docs/app.js 改接）已經要用到「打帳號登入」了，所以這支從
-- 草稿轉正、實際啟用（下面幾行不再是註解）。帳號不存在或帳號被停用都
-- 回傳 null（跟查得到但密碼打錯，前端看到的錯誤訊息要一樣，不能讓人
-- 從錯誤訊息猜出「這個帳號存不存在」）。
create or replace function resolve_username_email(p_username text)
returns text
language sql
security definer
set search_path = wei3, auth, pg_temp
as $$
  select au.email
  from profiles p
  join auth.users au on au.id = p.id
  where p.username = p_username
    and p.status = 'active';
$$;

grant execute on function resolve_username_email(text) to anon, authenticated;

-- 這支函式讀得到 auth.users，代表建立它的角色要有這個 schema 的存取
-- 權限——在 Supabase SQL editor 用專案自己的管理連線跑就沒問題，用一般
-- migration CLI 跑之前先確認權限，這塊在不同 Supabase 專案設定下偶爾
-- 會卡權限，值得先在測試專案跑一次確認沒問題再套用到別的環境。

  -- ════════ functions.sql：從原本場地目前的定義複製 ════════
  -- pg_get_functiondef 在 search_path 只有 pg_catalog 時，函式名稱、參數與回傳的資料表型別都會
  -- 寫成 public.xxx；只把宣告那段（AS 之前）的 public. 換成 wei3.，函式本體一字不動。
  -- 本體裡本來就沒有 public.（已確認），所以本體會繼續照 search_path 找資料表，下面再把
  -- 每支函式的 search_path 固定成 wei3。
  perform set_config('check_function_bodies', 'off', true);
  for _fn in
    select p.oid, p.proname
    from pg_proc p
    where p.pronamespace = 'public'::regnamespace
      and p.prokind = 'f'
      and p.proname <> 'notify_gas_webhook'   -- 原本場地同步 Google 試算表用的，wei3 沒有試算表
      and not exists (select 1 from pg_proc q where q.pronamespace = 'wei3'::regnamespace and q.proname = p.proname)
    order by p.oid
  loop
    perform set_config('search_path', 'pg_catalog', true);
    _def := pg_get_functiondef(_fn.oid);
    perform set_config('search_path', 'wei3, pg_temp', true);
    _pos := strpos(_def, E'\nAS $function$');
    if _pos = 0 or _def not like 'CREATE OR REPLACE FUNCTION public.%' then
      raise exception '函式 % 的格式不如預期，中止', _fn.proname;
    end if;
    _head := replace(left(_def, _pos), 'public.', 'wei3.');
    if _head ~ '\mpublic\M' then
      raise exception '函式 % 的宣告裡還有 public，中止', _fn.proname;
    end if;
    execute _head || substr(_def, _pos + 1);
  end loop;
  perform set_config('check_function_bodies', 'on', true);

  -- ── 每支函式的 search_path 固定成 wei3：就算呼叫端的 search_path 帶到 public，也不會讀寫到原本場地 ──
  for _fn in
    select p.oid::regprocedure as sig
    from pg_proc p
    where p.pronamespace = 'wei3'::regnamespace
      and p.prokind = 'f'
      and not exists (select 1 from unnest(coalesce(p.proconfig, '{}')) c where c like 'search_path=%')
  loop
    execute format('alter function %s set search_path = wei3, pg_temp', _fn.sig);
  end loop;

  grant all on all tables in schema wei3 to anon, authenticated, service_role;
  grant all on all sequences in schema wei3 to anon, authenticated, service_role;
  grant all on all routines in schema wei3 to anon, authenticated, service_role;

  -- ── 複製原本場地的「設定」（只有設定；記帳紀錄／營業日／每日帳目／帳號一律不複製）──
  -- 機台的「封存前累計」（carry_*）不複製，新場地從 0 開始（原本場地目前也都是 0）。
  insert into wei3.machines (machine_id, name, location, status, color, sort_order, note, category, icon)
  select machine_id, name, location, status, color, sort_order, note, category, icon from public.machines;
  insert into wei3.prizes (prize_id, machine_id, name, amount, sort_order, active)
  select prize_id, machine_id, name, amount, sort_order, active from public.prizes;
  insert into wei3.quick_amounts (qa_id, machine_id, type, amount, label, sort_order)
  select qa_id, machine_id, type, amount, label, sort_order from public.quick_amounts;
  insert into wei3.meter_rates (rate_id, machine_id, rate)
  select rate_id, machine_id, rate from public.meter_rates;
end
$wei3$;
